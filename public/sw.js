// Service worker mínimo para que la app se pueda instalar en el móvil.
// Red primero (siempre la última versión); si no hay conexión, sirve la interfaz guardada.
// La API nunca se cachea: la IA necesita conexión.
const CACHE = "my-school-v1";
const SHELL = ["/", "/index.html", "/styles.css", "/app.js", "/util.js", "/speech.js", "/conversation.js", "/icon.svg"];

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)));
  self.skipWaiting();
});

self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))));
  self.clients.claim();
});

self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== location.origin || url.pathname.startsWith("/api/")) return;
  e.respondWith(
    fetch(e.request)
      .then((res) => {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(e.request, copy));
        return res;
      })
      .catch(() => caches.match(e.request)),
  );
});
